    private bool SaveToRC(string filePath)
    {
        try
        {
            using var writer = new StreamWriter(filePath);
            writer.WriteLine("// Generated by CSharpRisohEditor");
            writer.WriteLine();

            foreach (var resource in Resources)
            {
                writer.WriteLine(resource.ToRC());
                writer.WriteLine();
            }

            return true;
        }
