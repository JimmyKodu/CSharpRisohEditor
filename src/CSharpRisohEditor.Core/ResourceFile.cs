    }

    /// <summary>
    /// Remove a resource
    /// </summary>
    public bool RemoveResource(ResourceEntry resource)
    {
        return Resources.Remove(resource);
    }

    /// <summary>
    /// Find resources by type
    /// </summary>
    public List<ResourceEntry> FindResourcesByType(ResourceType type)
    {
        return Resources.Where(r => r.Type == type).ToList();
